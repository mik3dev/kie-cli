var update = flag.Bool("update", false, "write testdata/live/SWEEP.md")

const (
	liveDir   = "../../testdata/live"
	sweepFile = "SWEEP.md"
)

type sweepResult struct {
	model     string
	taskTypes []string
	files     []string
	job       bool
	null      bool
}

// liveTaskTypes maps a schema file basename (model with "/" as "__") to its taskType.
func liveTaskTypes(t *testing.T) map[string][]string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(liveDir, "models.json"))
	if err != nil {
		t.Fatal(err)
	}
	var cat struct {
		Models []struct {
			Model    string   `json:"model"`
			TaskType []string `json:"taskType"`
		} `json:"models"`
	}
	if err := json.Unmarshal(b, &cat); err != nil {
		t.Fatal(err)
	}
	out := make(map[string][]string, len(cat.Models))
	for _, m := range cat.Models {
		out[strings.ReplaceAll(m.Model, "/", "__")] = m.TaskType
	}
	return out
}

// sweepOne runs every offline step on one doc and returns its result or the errors.
func sweepOne(d schema.Doc) (sweepResult, []string) {
	r := sweepResult{model: d.Model, job: d.IsJob(), null: d.Null()}
	if r.null || !r.job {
		return r, nil
	}
	var errs []string
	sch, err := d.InputSchema()
	if err != nil {
		return r, []string{"InputSchema: " + err.Error()}
	}
	sum, err := schema.Summarize(d)
	if err != nil {
		errs = append(errs, "Summarize: "+err.Error())
	}
	if _, err := schema.Validate(sch, map[string]any{}); err != nil {
		errs = append(errs, "Validate: "+err.Error())
	}
	names := map[string]bool{}
	for _, f := range sum.Fields {
		names[f.Name] = true
	}
	for _, v := range sum.Variants {
		for _, f := range v.Fields {
			names[f.Name] = true
		}
	}
	for k := range names {
		if upload.SchemaFileKey(sch, k) {
			r.files = append(r.files, k)
		}
	}
	sort.Strings(r.files)
	return r, errs
}

func TestSweepLiveSchemas(t *testing.T) {
	paths, err := filepath.Glob(filepath.Join(liveDir, "schemas", "*.json"))
	if err != nil || len(paths) == 0 {
		t.Fatalf("no live schemas found (err=%v)", err)
	}
	types := liveTaskTypes(t)
	var results []sweepResult
	failures := map[string][]string{}
	for _, p := range paths {
		base := strings.TrimSuffix(filepath.Base(p), ".json")
		d := load(t, p)
		if d.Model == "" {
			d.Model = strings.ReplaceAll(base, "__", "/")
		}
		r, errs := sweepOne(d)
		r.taskTypes = types[base]
		results = append(results, r)
		if len(errs) > 0 {
			failures[d.Model] = errs
		}
	}
	if len(failures) > 0 {
		var lines []string
		for m, e := range failures {
			lines = append(lines, fmt.Sprintf("%s: %s", m, strings.Join(e, "; ")))
		}
		sort.Strings(lines)
		t.Errorf("%d models failed:\n%s", len(failures), strings.Join(lines, "\n"))
	}
	if *update {
		if err := os.WriteFile(filepath.Join(liveDir, sweepFile), []byte(renderSweep(results, len(failures))), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func isInputToOutput(types []string) bool {
	for _, tt := range types {
		for _, p := range []string{"Image to", "Video to", "Audio to"} {
			if strings.Contains(tt, p) {
				return true
			}
		}
	}
	return false
}

func renderSweep(rs []sweepResult, errCount int) string {
	sort.Slice(rs, func(i, j int) bool { return rs[i].model < rs[j].model })
	var jobs, nonJob, null int
	var gaps, lines []string
	for _, r := range rs {
		switch {
		case r.null:
			null++
		case !r.job:
			nonJob++
		default:
			jobs++
			lines = append(lines, fmt.Sprintf("%s: %s", r.model, strings.Join(r.files, ", ")))
			if len(r.files) == 0 && isInputToOutput(r.taskTypes) {
				gaps = append(gaps, fmt.Sprintf("%s (%s)", r.model, strings.Join(r.taskTypes, ", ")))
			}
		}
	}
	var b strings.Builder
	b.WriteString("# Live schema sweep\n\nGenerated by `go test ./internal/schema/ -run Sweep -update`. Do not edit.\n\n")
	fmt.Fprintf(&b, "## Totals\n\n- schemas: %d\n- job: %d\n- non-job: %d\n- null: %d\n- errors: %d\n\n", len(rs), jobs, nonJob, null, errCount)
	b.WriteString("## Likely detection gaps (0 file fields, taskType Image/Video/Audio to ...)\n\n")
	if len(gaps) == 0 {
		b.WriteString("None.\n")
	}
	for _, g := range gaps {
		b.WriteString("- " + g + "\n")
	}
	b.WriteString("\n## File fields per model\n\n")
	for _, l := range lines {
		b.WriteString("- " + l + "\n")
	}
	return b.String()
}
