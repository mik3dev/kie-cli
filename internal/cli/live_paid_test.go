var (
	cdnURLRe = regexp.MustCompile(`^https://`)
)

// sanitize returns v with every https URL rewritten to
// https://cdn.example/<basename> (extension kept, query dropped). Strings that
// hold JSON (resultJson) are rewritten inside and re-encoded.
func sanitize(v any) any {
	switch x := v.(type) {
	case map[string]any:
		out := make(map[string]any, len(x))
		for k, e := range x {
			out[k] = sanitize(e)
		}
		return out
	case []any:
		out := make([]any, len(x))
		for i, e := range x {
			out[i] = sanitize(e)
		}
		return out
	case string:
		return sanitizeString(x)
	}
	return v
}

func sanitizeString(s string) string {
	if cdnURLRe.MatchString(s) {
		base := s
		if i := strings.IndexAny(base, "?#"); i >= 0 {
			base = base[:i]
		}
		return "https://cdn.example/" + filepath.Base(base)
	}
	t := strings.TrimSpace(s)
	if (strings.HasPrefix(t, "{") || strings.HasPrefix(t, "[")) && json.Valid([]byte(t)) {
		var inner any
		if err := json.Unmarshal([]byte(t), &inner); err == nil {
			if b, err := json.Marshal(sanitize(inner)); err == nil {
				return string(b)
			}
		}
	}
	return s
}

// captureRecord stores the sanitized recordInfo data of taskID as a fixture,
// only when KIE_E2E_CAPTURE=1. It refuses to write anything holding the API key.
func captureRecord(t *testing.T, taskID string) {
	t.Helper()
	if os.Getenv("KIE_E2E_CAPTURE") != "1" || taskID == "" {
		return
	}
	key := os.Getenv("KIE_API_KEY")
	if key == "" {
		t.Fatal("capture: KIE_API_KEY is empty")
	}
	c := api.New(key, os.Getenv)
	var data map[string]any
	req := api.Request{
		Method: "GET", Path: "/api/v1/jobs/recordInfo", Class: api.ClassRecord,
		Query: map[string][]string{"taskId": {taskID}},
	}
	if err := c.Do(context.Background(), req, &data); err != nil {
		t.Fatalf("capture: recordInfo %s: %v", taskID, err)
	}
	model, _ := data["model"].(string)
	if model == "" {
		t.Fatalf("capture: record %s has no model", taskID)
	}
	b, err := json.MarshalIndent(sanitize(data), "", "  ")
	if err != nil {
		t.Fatalf("capture: encode: %v", err)
	}
	b = append(b, '\n')
	if bytes.Contains(b, []byte(key)) {
		t.Fatal("refusing to write: fixture contains the API key")
	}
	if err := os.MkdirAll(recordsDir, 0o750); err != nil {
		t.Fatal(err)
	}
	name := strings.ReplaceAll(model, "/", "__") + ".json"
	if err := os.WriteFile(filepath.Join(recordsDir, name), b, 0o600); err != nil {
		t.Fatal(err)
	}
	t.Logf("captured record fixture: %s", name)
}

// captureOnCleanup registers the record capture for m's taskId so it runs even
// when a later assertion fails. Call it right after the run, before asserts.
func captureOnCleanup(t *testing.T, m map[string]any) {
	t.Helper()
	id, _ := m["taskId"].(string)
	if id == "" { // failed runs carry the id in error.details.taskId
		e, _ := m["error"].(map[string]any)
		d, _ := e["details"].(map[string]any)
		id, _ = d["taskId"].(string)
	}
	if id == "" {
		return
	}
	t.Cleanup(func() { captureRecord(t, id) })
}

func containsString(list []any, want string) bool {
	for _, e := range list {
		if s, ok := e.(string); ok && s == want {
			return true
		}
	}
	return false
}

// firstFile returns the path and kind of files[0], failing when absent or empty on disk.
func firstFile(t *testing.T, m map[string]any) (path, kind string) {
	t.Helper()
	files, _ := m["files"].([]any)
	if len(files) == 0 {
		t.Fatalf("no files in output (state=%v)", m["state"])
	}
	f, _ := files[0].(map[string]any)
	path, _ = f["path"].(string)
	kind, _ = f["kind"].(string)
	if st, err := os.Stat(path); err != nil || st.Size() == 0 {
		t.Fatalf("files[0] %q missing or empty: %v", filepath.Base(path), err)
	}
	return path, kind
}

func requireOK(t *testing.T, m map[string]any, code int) {
	t.Helper()
	if code != 0 {
		t.Fatalf("exit %d error=%v", code, m["error"])
	}
}

const zImagePrompt = "a red apple on white"

func TestLivePaid1Image(t *testing.T) {
	run := liveEnv(t)
	paid(t, 0.8)
	m, code := run("run", "z-image", "-p", "prompt="+zImagePrompt, "-p", "aspect_ratio=1:1", "--timeout", "5m", "--out", t.TempDir())
	captureOnCleanup(t, m)
	requireOK(t, m, code)
	path, kind := firstFile(t, m)
	if kind != "image" {
		t.Fatalf("kind = %q, want image", kind)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	paid1PNG = data
}

